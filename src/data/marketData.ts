// Helper to generate realistic candles for a symbol
export function generateCandlesForSymbol(symbol: string, timeframe: Timeframe, basePrice: number): Candle[] {
  const candles: Candle[] = [];
  let count = 40;
  let intervalMs = 5 * 60 * 1000; // 5 min for 1D

  if (timeframe === '1D') {
    count = 48;
    intervalMs = 5 * 60 * 1000;
  } else if (timeframe === '5D') {
    count = 60;
    intervalMs = 30 * 60 * 1000;
  } else if (timeframe === '1M') {
    count = 30;
    intervalMs = 24 * 60 * 60 * 1000;
  } else if (timeframe === '3M') {
    count = 65;
    intervalMs = 24 * 60 * 60 * 1000;
  } else if (timeframe === '1Y') {
    count = 52;
    intervalMs = 7 * 24 * 60 * 60 * 1000;
  } else {
    count = 60;
    intervalMs = 14 * 24 * 60 * 60 * 1000;
  }

  // Seed with pseudo-random deterministic variation based on symbol letters
  const seed = symbol.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  let currentClose = basePrice * (timeframe === '1D' ? 0.985 : 0.85);
  const now = Date.now();

  for (let i = 0; i < count; i++) {
    const timeOffset = (count - i) * intervalMs;
    const timestamp = now - timeOffset;
    const date = new Date(timestamp);
    
    // Trend slightly upward to match current bull market tone
    const pseudoRandom = Math.sin((seed + i * 17) % 360) * 0.6 + Math.cos((seed * 3 + i * 7) % 360) * 0.4;
    const deltaPercent = (pseudoRandom * 0.015) + 0.002;
    
    // For last candle, ensure it ends very close to basePrice
    let open = currentClose;
    let close = i === count - 1 ? basePrice : open * (1 + deltaPercent);
    const high = Math.max(open, close) + Math.abs(close - open) * (0.3 + Math.abs(pseudoRandom) * 0.5);
    const low = Math.min(open, close) - Math.abs(close - open) * (0.3 + Math.abs(pseudoRandom) * 0.4);
    const volume = Math.floor(150000 + Math.abs(pseudoRandom) * 850000);

    let timeString = '';
    if (timeframe === '1D' || timeframe === '5D') {
      timeString = date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false });
    } else {
      timeString = date.toLocaleDateString([], { month: 'short', day: 'numeric' });
    }

    candles.push({
      time: timeString,
      timestamp,
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      close: parseFloat(close.toFixed(2)),
      volume,
    });

    currentClose = close;
  }

  return candles;
}
